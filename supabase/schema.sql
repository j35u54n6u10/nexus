-- 8. Registrar Movimientos Iniciales de Entrada para dotar al inventario de stock de prueba
-- Usamos un bloque anónimo para registrar las entradas iniciales
DO $$
DECLARE
    r_prod RECORD;
BEGIN
    FOR r_prod IN SELECT id, nombre FROM productos LOOP
        -- Insertamos una entrada inicial de 35 unidades de promedio
        INSERT INTO movimientos (producto_id, tipo, cantidad, motivo)
        VALUES (r_prod.id, 'Entrada', 35.0, 'Carga inicial de inventario - Semilla');
    END LOOP;
END $$;

