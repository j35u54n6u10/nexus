-- 1. Limpieza de tablas (opcional, por si ya existen)
DROP TRIGGER IF EXISTS trg_procesar_movimiento_stock ON movimientos;
DROP FUNCTION IF EXISTS procesar_movimiento_stock();
DROP TABLE IF EXISTS movimientos;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS categorias;

-- 2. Crear Tabla de Categorías Base
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE
);

-- 3. Crear Tabla de Productos (Insumos)
CREATE TABLE productos (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    categoria_id BIGINT REFERENCES categorias(id) ON DELETE RESTRICT NOT NULL,
    unidad_medida TEXT NOT NULL, -- kg, g, litros, ml, unidades, paquetes, cajas
    stock_actual NUMERIC NOT NULL DEFAULT 0, -- Inmutable directamente
    stock_minimo NUMERIC NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Crear Tabla de Movimientos
CREATE TABLE movimientos (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    producto_id UUID REFERENCES productos(id) ON DELETE CASCADE NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('Entrada', 'Salida')),
    cantidad NUMERIC NOT NULL CHECK (cantidad > 0),
    motivo TEXT NOT NULL,
    usuario_id UUID REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(), -- Asignación automática en Supabase Auth
    usuario_email TEXT, -- Correo registrado del usuario responsable para auditoría directa
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Disparador (Trigger) para Cálculo Automático y Validación de Stock
CREATE OR REPLACE FUNCTION procesar_movimiento_stock()
RETURNS TRIGGER AS $$
DECLARE
    v_stock_actual NUMERIC;
    v_nombre_producto TEXT;
BEGIN
    -- Obtener el stock actual y nombre del producto bloqueando la fila para evitar condiciones de carrera (concurrencia)
    SELECT stock_actual, nombre INTO v_stock_actual, v_nombre_producto
    FROM productos 
    WHERE id = NEW.producto_id
    FOR UPDATE;

    IF v_stock_actual IS NULL THEN
        RAISE EXCEPTION 'Error: El producto especificado no existe.';
    END IF;

    IF NEW.tipo = 'Salida' THEN
        -- Validación de Egreso: No se permite si supera el stock actual
        IF v_stock_actual < NEW.cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para "%". Stock actual: % %, cantidad solicitada: % %.', 
                v_nombre_producto, v_stock_actual, (SELECT unidad_medida FROM productos WHERE id = NEW.producto_id), 
                NEW.cantidad, (SELECT unidad_medida FROM productos WHERE id = NEW.producto_id);
        END IF;
        
        -- Actualizar restando
        UPDATE productos 
        SET stock_actual = stock_actual - NEW.cantidad 
        WHERE id = NEW.producto_id;
    ELSIF NEW.tipo = 'Entrada' THEN
        -- Actualizar sumando
        UPDATE productos 
        SET stock_actual = stock_actual + NEW.cantidad 
        WHERE id = NEW.producto_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_procesar_movimiento_stock
BEFORE INSERT ON movimientos
FOR EACH ROW
EXECUTE FUNCTION procesar_movimiento_stock();

